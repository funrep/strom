package strom.fs2

import scala.reflect.ClassTag
import scala.util.Try
import cats.effect.kernel.{Concurrent, Spawn}
import cats.syntax.all.*
import _root_.fs2.{Chunk, Pull, Stream}
import strom.runtime.*

/** Runs compiled Ström segments inside fs2 streams.
 *
 *  Input chunks are lent to the segment without copying when they are array-backed with the
 *  right element type (`Chunk.toArraySlice`); every output chunk is a fresh primitive array
 *  wrapped with `Chunk.array` (one allocation per chunk, none per element). When a step uses
 *  up its work budget the stream `cede`s, so a long fused loop never monopolises a thread. */
object StromFs2:

  /** A one-input emitting segment as an fs2 `Pipe`. */
  def pipe[F[_]: Spawn, A: ClassTag, B](f: SegmentFactory[B], maxOut: Int = Segment.DefaultMaxOut, budget: Int = Segment.DefaultBudget)
      : _root_.fs2.Pipe[F, A, B] =
    in => toElements(runChunks[F](f, maxOut, budget, Vector(fromElements(in))))

  /** A two-input emitting segment (e.g. a fused zip of two streams). */
  def pipe2[F[_]: Spawn, A: ClassTag, B: ClassTag, C](f: SegmentFactory[C], maxOut: Int = Segment.DefaultMaxOut,
      budget: Int = Segment.DefaultBudget): (Stream[F, A], Stream[F, B]) => Stream[F, C] =
    (a, b) => toElements(runChunks[F](f, maxOut, budget, Vector(fromElements(a), fromElements(b))))

  /** A one-input fold segment: emits the single result when the input ends (or the fold stops early). */
  def fold[F[_]: Spawn, A: ClassTag, R](f: SegmentFactory[R], budget: Int = Segment.DefaultBudget): Stream[F, A] => Stream[F, R] =
    in => foldChunks[F, R](f, budget, Vector(fromElements(in)))

  def fold2[F[_]: Spawn, A: ClassTag, B: ClassTag, R](f: SegmentFactory[R], budget: Int = Segment.DefaultBudget)
      : (Stream[F, A], Stream[F, B]) => Stream[F, R] =
    (a, b) => foldChunks[F, R](f, budget, Vector(fromElements(a), fromElements(b)))

  // ------------------------------------------------------------------ fusion of plain fs2 code

  /** Fuses the pure operators of an ordinary fs2 stream expression:
   *  {{{ StromFs2.fused { in.map(f).filter(p).take(n).evalMap(io).map(g).fold(z)(op) } }}}
   *  Each maximal run of `map`, `filter`, `take`, `fold`, `flatMap` (onto `Stream.range`, with pure
   *  operators inside) and `zipWith` becomes one compiled segment; every other operator
   *  (effects, concurrency, time) is kept as written, between the fused runs. */
  inline def fused[S <: Stream[?, ?]](inline stream: S): S = ${ FusedMacro.fused[S]('stream) }

  /** The runs `fused` would compile for an expression, one per line (a compile-time constant). */
  inline def fusedPlan(inline stream: Stream[?, ?]): String = ${ FusedMacro.plan('stream) }

  /** Like [[fused]], and each fused run is also spread over `parallelism` workers where that is
   *  safe: stateless operators (`map`, `filter`, `flatMap`, `collect`, …) process chunks
   *  concurrently, stateful ones (`take`, `scan`, `zip`, …) run on one instance, and a `fold`
   *  with a recognised associative operator (`_ + _`, `_ * _`, `math.max`, … over Ints/Longs, with
   *  its identity as the start value) folds chunks concurrently. Output order and results are
   *  exactly those of the sequential stream.
   *
   *  The functions passed to fused operators must be pure: they run on several threads at once.
   *  Capturing a `var` is a compile error; other shared mutable state (a mutable collection, a
   *  non-thread-safe object) is not detected. Needs `Concurrent[F]`, else the run stays sequential.
   *  Worth it when the per-element work is substantial. */
  inline def fusedPar[S <: Stream[?, ?]](parallelism: Int)(inline stream: S): S =
    ${ FusedMacro.fusedPar[S]('parallelism, 'stream) }

  /** The runs `fusedPar` would compile for an expression, with their parallel tiers. */
  inline def fusedParPlan(inline stream: Stream[?, ?]): String = ${ FusedMacro.parPlan('stream) }

  /** Entry point used by the code generated by [[fused]]. `inputs` are `Stream[F, ?]`s with
   *  element class tags `tags`; `cede` is an `F[Unit]` or null. */
  def fusedRun[F[_], B](f: SegmentFactory[?], inputs: Vector[Any], tags: Vector[ClassTag[?]], cede: Any,
                        maxOut: Int = Segment.DefaultMaxOut, budget: Int = Segment.DefaultBudget): Stream[F, B] =
    val ins = inputs.zip(tags).map((s, t) =>
      fromElements(s.asInstanceOf[Stream[F, Any]])(using t.asInstanceOf[ClassTag[Any]]))
    val out = drive[F](f, maxOut, budget, ins, Option(cede.asInstanceOf[F[Unit]]))
    if f.isFold then out.map(c => java.lang.reflect.Array.get(c.array, c.offset).asInstanceOf[B])
    else toElements(out)

  /** Entry point used by the code generated by [[fusedPar]]: runs `plan` over `input` (a
   *  `Stream[F, ?]` with element class tag `tag`). Replicated tiers and partial folds use
   *  `parEvalMap` (ordered) over a pool of reusable instances; single tiers run sequentially. */
  def fusedParRun[F[_], B](plan: ParallelPlan[?], input: Any, tag: ClassTag[?], parallelism: Int,
      maxOut: Int = Segment.DefaultMaxOut, budget: Int = Segment.DefaultBudget)(using F: Concurrent[F]): Stream[F, B] =
    require(parallelism > 0, "parallelism must be positive")
    def cpu[X](x: => X): F[X] = F.unit.map(_ => x)
    // `parEvalMap` works ahead of demand, and pulls its upstream ahead too. Failures, of the work
    // or of the upstream, are held as values and raised only when their turn comes in order,
    // after the outputs produced before them: work that is never needed (past a downstream
    // `take`) can't fail the stream.
    def ahead(s: Stream[F, ArrayChunk])(work: ArrayChunk => Processed): Stream[F, ArrayChunk] =
      s.attempt.parEvalMap(parallelism) {
        case Right(c) => cpu(work(c))
        case Left(e)  => F.pure(Processed(ArrayChunk(Array.empty[Any], 0, 0), e))
      }.flatMap { p =>
        val out = if p.chunk.length > 0 then Stream.emit(p.chunk) else Stream.empty
        if p.error eq null then out else out ++ Stream.raiseError[F](p.error)
      }
    val in = fromElements(input.asInstanceOf[Stream[F, Any]])(using tag.asInstanceOf[ClassTag[Any]])
    val last = plan.tiers.foldLeft(in) { (s, tier) =>
      tier match
        case Tier.Replicated(f) =>
          val pool = SegmentPool(f, maxOut, budget)
          ahead(s)(c => pool.use(seg => Chunks.processUntilFailure(seg, c)))
        case Tier.PartialFold(f, combine) =>
          val pool = SegmentPool(f, maxOut, budget)
          val partials = ahead(s)(c => Try(pool.use(seg => Chunks.partialFold(seg, c))) match
            case scala.util.Success(r) => Processed(ArrayChunk.single(r), null)
            case scala.util.Failure(e) => Processed(ArrayChunk(Array.empty[Any], 0, 0), e))
            .filter(_.length > 0).map(c => java.lang.reflect.Array.get(c.array, c.offset))
          Stream.eval(partials.compile.fold(Option.empty[Any])((acc, r) => Some(acc.fold(r)(combine(_, r))))
            .map(_.getOrElse(Chunks.end(f.create(maxOut, budget))._2)))
            .map(ArrayChunk.single)
        case Tier.Single(f) => runChunks[F](f, maxOut, budget, Vector(s))
    }
    if plan.isFold then last.map(c => java.lang.reflect.Array.get(c.array, c.offset).asInstanceOf[B])
    else toElements(last)

  // ------------------------------------------------------------------ core loop

  private def fromElements[F[_], A](s: Stream[F, A])(using tag: ClassTag[A]): Stream[F, ArrayChunk] =
    s.chunks.map { c =>
      val slice = c.toArraySlice(using tag.asInstanceOf[ClassTag[Any]])
      ArrayChunk(slice.values, slice.offset, slice.size)
    }

  private def toElements[F[_], B](s: Stream[F, ArrayChunk]): Stream[F, B] =
    s.flatMap { c =>
      if c.length == 0 then Stream.empty
      else
        val component = c.array.getClass.getComponentType
        val arr = c.array.asInstanceOf[Array[B]]
        Stream.chunk(Chunk.array(arr, c.offset, c.length)(using ClassTag(component)))
    }

  private def foldChunks[F[_]: Spawn, R](f: SegmentFactory[R], budget: Int, inputs: Vector[Stream[F, ArrayChunk]])
      : Stream[F, R] =
    runChunks[F](f, 1, budget, inputs).map(c => java.lang.reflect.Array.get(c.array, c.offset).asInstanceOf[R])

  /** Drives a segment over chunk streams. Emits output chunks (fresh arrays); a fold emits one
   *  single-element chunk holding its result. */
  private def runChunks[F[_]: Spawn](f: SegmentFactory[?], maxOut: Int, budget: Int,
      inputs: Vector[Stream[F, ArrayChunk]]): Stream[F, ArrayChunk] =
    drive[F](f, maxOut, budget, inputs, Some(Spawn[F].cede))

  /** The driving loop. `cede`, when available, runs whenever a step used up its budget; without
   *  it (e.g. `Pure` streams) the loop simply continues. */
  private def drive[F[_]](f: SegmentFactory[?], maxOut: Int, budget: Int,
      inputs: Vector[Stream[F, ArrayChunk]], cede: Option[F[Unit]]): Stream[F, ArrayChunk] =
    require(inputs.size == f.numInputs, s"segment expects ${f.numInputs} inputs, got ${inputs.size}")
    Stream.suspend {
      // A fresh, thread-confined segment per stream run; fs2 runs a Pull sequentially.
      val runner = Runner(f, maxOut, budget)

      // Each port is read through a StepLeg, which keeps its scope across pulls. A leg's head is
      // a chunk of ArrayChunks; the segment takes them one at a time (`pending`).
      def go(legs: Vector[Leg[F]]): Pull[F, ArrayChunk, Unit] = Pull.suspend {
        runner.next() match
          case Runner.NeedInput(p) =>
            legs(p) match
              case Leg.Going(l, pending) if !pending.isEmpty =>
                offer(p, pending(0))
                go(legs.updated(p, Leg.Going(l, pending.drop(1))))
              case leg =>
                val step = leg match
                  case Leg.Start(s)      => s.pull.stepLeg
                  case Leg.Going(l, _)   => l.stepLeg
                  case Leg.Finished()    => Pull.pure(None)
                step.flatMap {
                  case Some(l) => go(legs.updated(p, Leg.Going(l, l.head)))
                  case None =>
                    runner.endOfInput(p)
                    go(legs.updated(p, Leg.Finished()))
                }
          case Runner.Emit =>
            Pull.output1(ArrayChunk.copyOut(runner)) >> go(legs)
          case Runner.Yield =>
            cede match
              case Some(c) => Pull.eval(c) >> go(legs)
              case None    => go(legs)
          case Runner.Done =>
            if runner.isFold then Pull.output1(ArrayChunk.single(runner.result)) else Pull.done
      }

      def offer(p: Int, c: ArrayChunk): Unit = runner.offer(p, c.array, c.offset, c.length)

      go(inputs.map(Leg.Start(_))).stream
    }

  private enum Leg[F[_]]:
    case Start(s: Stream[F, ArrayChunk])
    case Going(leg: Stream.StepLeg[F, ArrayChunk], pending: Chunk[ArrayChunk])
    case Finished()
