package strom.zio

import scala.reflect.ClassTag
import scala.util.Try
import _root_.zio.{Chunk, Trace, ZIO}
import _root_.zio.stream.{ZChannel, ZPipeline, ZStream}
import strom.runtime.*

/** Runs compiled one-input Ström segments as ZIO stream pipelines.
 *
 *  Input chunks are read with `ZChannel.readWithCause` and copied once into a primitive array
 *  (`Chunk.toArray`); outputs are fresh primitive arrays wrapped by `Chunk.fromArray`. When a
 *  step uses up its work budget the channel runs `ZIO.yieldNow`. */
object StromZio:

  def pipeline[A: ClassTag, B](f: SegmentFactory[B], maxOut: Int = Segment.DefaultMaxOut, budget: Int = Segment.DefaultBudget)(
      using Trace): ZPipeline[Any, Nothing, A, B] =
    require(f.numInputs == 1 && !f.isFold, "pipeline expects a one-input emitting segment")
    ZPipeline.fromChannel(channel[A, B](f, maxOut, budget))

  /** A one-input fold: the stream's single element is the result. */
  def fold[A: ClassTag, R](f: SegmentFactory[R], budget: Int = Segment.DefaultBudget)(using Trace): ZPipeline[Any, Nothing, A, R] =
    require(f.numInputs == 1 && f.isFold, "fold expects a one-input fold segment")
    ZPipeline.fromChannel(channel[A, R](f, 1, budget))

  def runFold[Rq, E, A: ClassTag, R](f: SegmentFactory[R], budget: Int = Segment.DefaultBudget)(s: ZStream[Rq, E, A])(
      using Trace): ZIO[Rq, E, R] =
    s.via(fold[A, R](f, budget)).runHead.map(_.get)

  /** Fuses the pure operators of an ordinary ZStream expression: maximal runs of `map`,
   *  `filter`, `take` and `flatMap` (onto `ZStream.range`) become compiled segments; every other
   *  operator is kept as written. See [[FusedMacro]] for the operator list. */
  inline def fused[S <: ZStream[?, ?, ?]](inline stream: S): S = ${ FusedMacro.fused[S]('stream) }

  /** The runs `fused` would compile for an expression, one per line (a compile-time constant). */
  inline def fusedPlan(inline stream: ZStream[?, ?, ?]): String = ${ FusedMacro.plan('stream) }

  /** Entry point used by the code generated by [[fused]]: drives a segment over `inputs`
   *  (`ZStream[R, E, ?]`s with element class tags `tags`), pulling each port with `toPull`. */
  def fusedRun[R, E, B](f: SegmentFactory[?], inputs: Vector[Any], tags: Vector[ClassTag[?]], maxOut: Int, budget: Int)(
      using Trace): ZStream[R, E, B] =
    val ins = inputs.zip(tags).map((s, t) => fromElements(s.asInstanceOf[ZStream[R, E, Any]], t.asInstanceOf[ClassTag[Any]]))
    toElements(driveChunks[R, E](f, maxOut, budget, ins))

  /** Like [[fused]], and each fused run is also spread over `parallelism` workers where that is
   *  safe: stateless operators (`map`, `filter`, `flatMap`, `collect`, …) process chunks
   *  concurrently (`mapZIOPar`, order preserved), stateful ones (`take`, `scan`, `zip`, …) run on
   *  one instance. Output is exactly that of the sequential stream.
   *
   *  The functions passed to fused operators must be pure: they run on several fibers at once.
   *  Capturing a `var` is a compile error; other shared mutable state (a mutable collection, a
   *  non-thread-safe object) is not detected. Worth it when the per-element work is substantial. */
  inline def fusedPar[S <: ZStream[?, ?, ?]](parallelism: Int)(inline stream: S): S =
    ${ FusedMacro.fusedPar[S]('parallelism, 'stream) }

  /** The runs `fusedPar` would compile for an expression, with their parallel tiers. */
  inline def fusedParPlan(inline stream: ZStream[?, ?, ?]): String = ${ FusedMacro.parPlan('stream) }

  /** Entry point used by the code generated by [[fusedPar]]: runs `plan` over `input` (a
   *  `ZStream[R, E, ?]` with element class tag `tag`). */
  def fusedParRun[R, E, B](plan: ParallelPlan[?], input: Any, tag: ClassTag[?], parallelism: Int, maxOut: Int, budget: Int)(
      using Trace): ZStream[R, E, B] =
    require(parallelism > 0, "parallelism must be positive")
    val in = fromElements(input.asInstanceOf[ZStream[R, E, Any]], tag.asInstanceOf[ClassTag[Any]])
    // `mapZIOPar` works ahead of demand, and pulls its upstream ahead too. Failures, of the work
    // (a defect, like a throwing `map`) or of the upstream, are held as values and raised only
    // when their turn comes in order, after the outputs produced before them: work that is never
    // needed can't fail the stream.
    def ahead(s: ZStream[R, E, ArrayChunk])(work: ArrayChunk => Processed): ZStream[R, E, ArrayChunk] =
      val empty = ArrayChunk(Array.empty[Any], 0, 0)
      s.map(Right(_): Either[_root_.zio.Cause[E], ArrayChunk]).catchAllCause(c => ZStream.succeed(Left(c)))
        .mapZIOPar(parallelism) {
          case Right(c) => ZIO.succeed(work(c) match
            case Processed(out, null) => (out, null)
            case Processed(out, e)    => (out, _root_.zio.Cause.die(e)))
          case Left(c) => ZIO.succeed((empty, c))
        }
        .flatMap { (chunk, cause) =>
          val out = if chunk.length > 0 then ZStream.succeed(chunk) else ZStream.empty
          if cause eq null then out else out ++ ZStream.failCause(cause)
        }
    val last = plan.tiers.foldLeft(in) { (s, tier) =>
      tier match
        case Tier.Replicated(f) =>
          val pool = SegmentPool(f, maxOut, budget)
          ahead(s)(c => pool.use(seg => Chunks.processUntilFailure(seg, c)))
        case Tier.PartialFold(f, combine) =>
          val pool = SegmentPool(f, maxOut, budget)
          ZStream.fromZIO(
            ahead(s)(c => Try(pool.use(seg => Chunks.partialFold(seg, c))) match
              case scala.util.Success(r) => Processed(ArrayChunk.single(r), null)
              case scala.util.Failure(e) => Processed(ArrayChunk(Array.empty[Any], 0, 0), e))
              .filter(_.length > 0).map(c => java.lang.reflect.Array.get(c.array, c.offset))
              .runFold(Option.empty[Any])((acc, r) => Some(acc.fold(r)(combine(_, r))))
              .map(_.getOrElse(Chunks.end(f.create(maxOut, budget))._2))
          ).map(ArrayChunk.single)
        case Tier.Single(f) => driveChunks[R, E](f, maxOut, budget, Vector(s))
    }
    if plan.isFold then last.map(c => java.lang.reflect.Array.get(c.array, c.offset).asInstanceOf[B])
    else toElements(last)

  // ------------------------------------------------------------------ core loop

  private def fromElements[R, E, A](s: ZStream[R, E, A], tag: ClassTag[A])(using Trace): ZStream[R, E, ArrayChunk] =
    s.chunks.map(c => ArrayChunk(primitiveArray(c, tag), 0, c.length))

  private def toElements[R, E, B](s: ZStream[R, E, ArrayChunk])(using Trace): ZStream[R, E, B] =
    s.mapConcatChunk { c =>
      if c.length == 0 then Chunk.empty
      else
        val dst = java.lang.reflect.Array.newInstance(c.array.getClass.getComponentType, c.length)
        System.arraycopy(c.array, c.offset, dst, 0, c.length)
        Chunk.fromArray(dst.asInstanceOf[Array[B]])
    }

  /** Drives a segment over chunk streams, pulling each port with `toPull`. Emits output chunks;
   *  a fold emits one single-element chunk holding its result. */
  private def driveChunks[R, E](f: SegmentFactory[?], maxOut: Int, budget: Int, inputs: Vector[ZStream[R, E, ArrayChunk]])(
      using Trace): ZStream[R, E, ArrayChunk] =
    ZStream.unwrapScoped[R] {
      ZIO.foreach(inputs)(_.toPull).map { pulls =>
        // A fresh, thread-confined segment per stream run.
        val runner = Runner(f, maxOut, budget)
        val pending = Array.fill(inputs.size)(Chunk.empty[ArrayChunk])
        var done = false
        def offer(p: Int, c: ArrayChunk): Unit = runner.offer(p, c.array, c.offset, c.length)
        def loop: ZIO[R, Option[E], Chunk[ArrayChunk]] = ZIO.suspendSucceed {
          if done then ZIO.fail(None)
          else runner.next() match
            case Runner.NeedInput(p) =>
              if pending(p).nonEmpty then
                offer(p, pending(p).head)
                pending(p) = pending(p).tail
                loop
              else
                pulls(p).foldZIO(
                  {
                    case None => runner.endOfInput(p); loop
                    case Some(e) => ZIO.fail(Some(e))
                  },
                  chunk => { pending(p) = chunk; loop })
            case Runner.Emit => ZIO.succeed(Chunk.single(ArrayChunk.copyOut(runner)))
            case Runner.Yield => ZIO.yieldNow *> loop
            case Runner.Done =>
              done = true
              if runner.isFold then ZIO.succeed(Chunk.single(ArrayChunk.single(runner.result))) else ZIO.fail(None)
        }
        ZStream.repeatZIOChunkOption(loop)
      }
    }

  /** The chunk as an array of its primitive element type (generic, so no `Object[]` cast). */
  private def primitiveArray[A](c: Chunk[A], tag: ClassTag[A]): AnyRef = c.toArray(using tag)

  private def channel[A, O](f: SegmentFactory[O], maxOut: Int, budget: Int)(using tag: ClassTag[A], t: Trace)
      : ZChannel[Any, Nothing, Chunk[A], Any, Nothing, Chunk[O], Any] =
    ZChannel.suspend {
      // A fresh, thread-confined segment per run; a channel runs its steps sequentially.
      val runner = Runner(f, maxOut, budget)

      def go(): ZChannel[Any, Nothing, Chunk[A], Any, Nothing, Chunk[O], Any] =
        runner.next() match
          case Runner.NeedInput(_) =>
            ZChannel.readWithCause(
              (in: Chunk[A]) => ZChannel.suspend {
                val arr = in.toArray
                runner.offer(0, arr, 0, arr.length)
                go()
              },
              cause => ZChannel.refailCause(cause),
              _ => ZChannel.suspend { runner.endOfInput(0); go() },
            )
          case Runner.Emit =>
            ZChannel.write(Chunk.fromArray(ArrayChunk.copyOut(runner).array.asInstanceOf[Array[O]])) *> ZChannel.suspend(go())
          case Runner.Yield =>
            ZChannel.fromZIO(ZIO.yieldNow) *> ZChannel.suspend(go())
          case Runner.Done =>
            if runner.isFold then ZChannel.write(Chunk.single(runner.result)) else ZChannel.unit

      go()
    }
