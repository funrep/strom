import sbt._
import scala.util.Random

/** Generates random fs2 / ZIO operator chains for the fuzz suites. `.fused` is a macro, so it
 *  must see the chain in the source: each case is written out as code. Every chain mixes pure
 *  operators (fused) with effects that log to a `Ref` (kept), and some throw on one value.
 *
 *  STROM_FUZZ_CASES (default 120) and STROM_FUZZ_SEED (default 1) control the output. */
object FuzzGen {
  private def cases: Int = sys.env.get("STROM_FUZZ_CASES").map(_.toInt).getOrElse(120)
  private def seed: Long = sys.env.get("STROM_FUZZ_SEED").map(_.toLong).getOrElse(1L)

  private final case class Lib(stream: String, range: String, one: String, many: String, effects: Seq[(Random, String) => String],
                               take: Int => String, drop: Int => String, mapAccum: String, zipEff: (Random, String) => String,
                               ends: Seq[String])

  private val fs2Lib = Lib(
    stream = "Stream", range = "Stream.range", one = "Stream.emit", many = "Stream.emits",
    effects = Seq(
      (r, t) => s""".evalMap(x => ef(log, "$t", x).as(x))""",
      (r, t) => s""".evalTap(x => ef(log, "$t", x))""",
      (r, t) => s".chunkLimit(${1 + r.nextInt(7)}).unchunks",
      (r, t) => s""".evalFilter(x => ef(log, "$t", x).as(x % ${2 + r.nextInt(3)} != 0))""",
    ),
    take = n => s".take(${n}L)", drop = n => s".drop(${n}L)",
    mapAccum = ".mapAccumulate(0)((s, x) => (s + x, x - s)).map(_._2)",
    zipEff = (r, t) => s""".zipWith(Stream.range(0, ${50 + r.nextInt(400)}).covary[IO].evalMap(y => ef(log, "$t", y).as(y)))(_ - _)""",
    ends = Seq(".fold(0)(_ + _)", ".foldMonoid", ".fold(1)((a, x) => a * 31 + x)"),
  )

  private val zioLib = Lib(
    stream = "ZStream", range = "ZStream.range", one = "ZStream.succeed", many = "ZStream.fromIterable",
    effects = Seq(
      (r, t) => s""".mapZIO(x => ef(log, "$t", x).as(x))""",
      (r, t) => s""".tap(x => ef(log, "$t", x))""",
      (r, t) => s".rechunk(${1 + r.nextInt(7)})",
      (r, t) => s""".filterZIO(x => ef(log, "$t", x).as(x % ${2 + r.nextInt(3)} != 0))""",
    ),
    take = n => s".take(${n}L)", drop = n => s".drop($n)",
    mapAccum = ".mapAccum(0)((s, x) => (s + x, x - s))",
    zipEff = (r, t) => s""".zipWith(ZStream.range(0, ${50 + r.nextInt(400)}).mapZIO(y => ef(log, "$t", y).as(y)))(_ - _)""",
    ends = Nil,
  )

  private def pureOp(r: Random, lib: Lib): String = r.nextInt(15) match {
    case 0 | 1 => s".map(x => x * ${1 + r.nextInt(5)} + ${r.nextInt(9) - 4})"
    case 2 | 3 => s".filter(x => x % ${2 + r.nextInt(4)} != ${r.nextInt(2)})"
    case 4     => lib.take(r.nextInt(120))
    case 5     => lib.drop(r.nextInt(10))
    case 6     => s".takeWhile(x => x < ${40 + r.nextInt(200)})"
    case 7     => s".dropWhile(x => x < ${r.nextInt(20)})"
    case 8     => ".scan(0)((a, x) => a + x)"
    case 9     => ".zipWithIndex.map((x, i) => x + i.toInt)"
    case 10    => s".collect { case x if x % 3 != ${r.nextInt(3)} => x * 2 }"
    case 11    => lib.mapAccum
    case 12    => r.nextInt(3) match {
      case 0 => s".flatMap(x => ${lib.range}(0, x & 3))"
      case 1 => s".flatMap(x => ${lib.many}(List(x, x + 1)))"
      case _ => s".flatMap(x => ${lib.one}(x * 2))"
    }
    case 13    => s".zipWith(${lib.range}(0, ${50 + r.nextInt(400)}))(_ + _)"
    case _     => s".map(x => x ^ (x >>> ${1 + r.nextInt(4)}))"
  }

  private def chain(r: Random, lib: Lib, id: Int): String = {
    val n = 3 + r.nextInt(8)
    val ops = (0 until n).map { i =>
      val tag = s"c$id.$i"
      r.nextInt(10) match {
        case 0 | 1 => lib.effects(r.nextInt(lib.effects.size))(r, tag)
        case 2 if r.nextInt(3) == 0 => lib.zipEff(r, "z" + tag) // a zipped side's effects
        case _ => pureOp(r, lib)
      }
    }
    // One chain in five throws on one value somewhere.
    val withBoom =
      if (r.nextInt(5) == 0) {
        val at = r.nextInt(ops.size + 1)
        ops.patch(at, Seq(s".map(x => if x == ${r.nextInt(40)} then throw Boom() else x)"), 0)
      } else ops
    val end = if (lib.ends.nonEmpty && r.nextInt(4) == 0) lib.ends(r.nextInt(lib.ends.size)) else ""
    "in" + withBoom.mkString + end
  }

  private def write(dir: File, pkg: String, header: String, lib: Lib, sig: String): Seq[File] = {
    val r = new Random(seed)
    val body = (0 until cases).map { i =>
      val c = chain(r, lib, i)
      val code = c.replace("\\", "\\\\").replace("\"", "\\\"")
      s"""    FuzzCase("$i", "$code", (in, log) => $c, (in, log) => $c.fused, (in, log) => $c.fusedPar(3)),"""
    }.mkString("\n")
    val file = dir / "strom" / pkg / "FuzzCases.scala"
    IO.write(file,
      s"""package strom.$pkg
         |
         |// Generated by project/FuzzGen.scala (seed $seed). Do not edit.
         |$header
         |
         |final case class FuzzCase(name: String, code: String, plain: $sig, fused: $sig, par: $sig)
         |
         |object FuzzCases:
         |  val cases: Vector[FuzzCase] = Vector(
         |$body
         |  )
         |""".stripMargin)
    Seq(file)
  }

  def fs2(dir: File): Seq[File] = write(dir, "fs2",
    """import cats.effect.{IO, Ref}
      |import _root_.fs2.Stream
      |import FuzzSupport.*""".stripMargin,
    fs2Lib, "(Stream[IO, Int], Ref[IO, Vector[String]]) => Stream[IO, Int]")

  def zio(dir: File): Seq[File] = write(dir, "zio",
    """import _root_.zio.Ref
      |import _root_.zio.stream.ZStream
      |import FuzzSupport.*""".stripMargin,
    zioLib, "(ZStream[Any, Nothing, Int], Ref[Vector[String]]) => ZStream[Any, Nothing, Int]")
}
